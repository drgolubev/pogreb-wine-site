def case_url(c):
    return 'case-' + c['slug'] + '.html'

def case_card(c, extra=''):
    return ('<a class="ocard' + extra + '" href="' + case_url(c) + '"><div class="ocard-media"><img src="' + c['card'] + '"' + (' style="object-position:' + c['card_pos'] + '"' if c.get('card_pos') else '') + ' alt="' + c['card_alt'] + '" loading="lazy"></div>'
            '<div class="ocard-body"><span class="ocard-meta">' + c['city'] + ' · ' + c['kind'] + '</span><h3>' + c['title'] + '</h3><p>' + c['short'] + '</p>'
            '<span class="tcard-go"><i></i>Смотреть объект</span></div></a>')

def gallery_figure(path, cap, ratio=None):
    if path.endswith('.mp4'):
        poster = path[:-4] + '-poster.jpg'
        return ('<figure style="aspect-ratio:' + (ratio or '9/16') + '"><video src="' + path + '" poster="' + poster + '" muted loop playsinline preload="metadata" aria-label="' + cap + '"></video><figcaption>' + cap + '</figcaption></figure>')
    return '<figure style="aspect-ratio:' + (ratio or '3/4') + '"><img src="' + path + '" alt="' + cap + '" loading="lazy"><figcaption>' + cap + '</figcaption></figure>'

def catalog_rows(n):
    rows, rem, t = [], n, 2
    while rem > 0:
        if rem in (1, 2, 3): rows.append(rem); break
        if rem == 4: rows += [2, 2]; break
        rows.append(t); rem -= t; t = 5 - t
    return rows

def case_catalog(items):
    # ряды по 2 широкие и по 3 обычные карточки, чтобы сетка всегда закрывалась без дыр
    out, i = [], 0
    for r in catalog_rows(len(items)):
        cls = {1: ' ocard-full', 2: ' ocard-w', 3: ''}[r]
        for c in items[i:i + r]: out.append(case_card(c, cls))
        i += r
    return '<div class="ogrid ogrid-cat">' + ''.join(out) + '</div>'
